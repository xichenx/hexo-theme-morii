'use strict';
const fs = require('node:fs');
const path = require('node:path');
const yaml = require('js-yaml');
const features = {
  about: { title: '关于', type: 'about' }, categories: { title: '分类', type: 'categories' }, tags: { title: '标签', type: 'tags' },
  essay: { title: '即刻', type: 'essay', data: 'essay' }, album: { title: '相册', type: 'album', data: 'album' }, link: { title: '友链', type: 'link', data: 'link' },
  music: { title: '音乐馆', type: 'music', explore: true }, cinema: { title: '电影院', generated: true, explore: true, data: 'cinema' },
  comments: { title: '留言板', type: 'page', explore: true }, fcircle: { title: '朋友圈', type: 'fcircle', explore: true },
  series: { title: '专题与系列', generated: true, data: 'series' }
};
const header = '# Generated by hexo morii:init.\n# 站名、作者、语言与简介继承博客 _config.yml，无需重复填写。\n# 可选配置参考 Morii 文档；已有配置不会被覆盖。\n';
const exists = file => { try { return fs.lstatSync(file); } catch (error) { if (error.code === 'ENOENT') return null; throw error; } };
const inside = (base, file) => file.startsWith(base + path.sep);
function assertSafe(base, relative) {
  const target = path.resolve(base, relative);
  if (!inside(base, target)) throw new Error(`Path must stay inside the blog: ${relative}`);
  let parent = path.dirname(target);
  while (parent !== base) {
    const stat = exists(parent);
    if (stat && (stat.isSymbolicLink() || !stat.isDirectory())) throw new Error(`Refusing to write through a linked or non-directory path: ${path.relative(base, parent)}`);
    parent = path.dirname(parent);
  }
  return target;
}
const sameContent = (file, content) => { const stat = exists(file); return stat?.isFile() && !stat.isSymbolicLink() && fs.readFileSync(file, 'utf8') === content; };
function selected(value) {
  const items = value == null ? ['about', 'categories', 'tags'] : typeof value === 'string' ? value.split(',').map(item => item.trim()).filter(Boolean) : Array.isArray(value) ? value : null;
  if (!items) throw new Error('--pages expects a comma-separated list.');
  if (items.length === 1 && items[0] === 'none') return [];
  if (items.some(item => typeof item !== 'string' || !Object.hasOwn(features, item))) throw new Error(`Unknown page. Choose: ${Object.keys(features).join(', ')} or none.`);
  return [...new Set(items)];
}
function pagePath(source, id) {
  const candidates = ['index.md', 'index.markdown', 'index.html', 'index.htm'].map(name => path.join(source, id, name)).concat([path.join(source, `${id}.md`), path.join(source, `${id}.markdown`)]);
  const found = candidates.find(exists);
  let url = found && path.dirname(found) === source ? `/${id}.html` : `/${id}/`;
  if (found && exists(found)?.isFile() && !exists(found).isSymbolicLink()) {
    const front = fs.readFileSync(found, 'utf8').match(/^---\r?\n([\s\S]*?)\r?\n---/);
    if (front) try {
      const permalink = yaml.load(front[1])?.permalink;
      if (typeof permalink === 'string' && /^\/(?!\/)/.test(permalink) && !/[\\?#\u0000-\u001f]/.test(permalink) && !permalink.split('/').includes('..')) url = permalink;
    } catch { /* Preserve the existing page without rewriting its metadata. */ }
  }
  return { found, url };
}
function plan(baseDirectory, options = {}, translate = value => value) {
  const base = fs.realpathSync(baseDirectory);
  const inputBase = path.resolve(baseDirectory);
  const inputSource = path.resolve(inputBase, options.sourceDir || 'source');
  const source = inside(base, inputSource) ? inputSource : path.resolve(base, path.relative(inputBase, inputSource));
  if (!inside(base, source)) throw new Error('source_dir must be a directory inside the blog.');
  assertSafe(base, path.relative(base, path.join(source, '.morii-check')));
  const pages = selected(options.pages);
  if (options.musicId && !pages.includes('music')) pages.push('music');
  const provider = options.comments || 'none';
  if (!['none', 'twikoo', 'waline'].includes(provider)) throw new Error('--comments must be none, twikoo or waline.');
  if (provider !== 'none' && !pages.includes('comments')) pages.push('comments');
  const endpoint = typeof options.serverURL === 'string' ? options.serverURL.trim() : '';
  if (endpoint && provider === 'none') throw new Error('Choose --comments twikoo or waline with --server-url.');
  if (provider !== 'none' && !endpoint) throw new Error('Set --server-url when enabling comments.');
  if (provider === 'waline') {
    let url; try { url = new URL(endpoint); } catch { throw new Error('Waline requires an HTTP(S) server URL.'); }
    if (!/^https?:$/.test(url.protocol) || url.username || url.password) throw new Error('Waline requires an HTTP(S) server URL without credentials.');
  }
  if (options.github && (typeof options.github !== 'string' || !/^[a-z\d](?:[a-z\d-]{0,37}[a-z\d])?$/i.test(options.github))) throw new Error('Invalid GitHub username.');
  if (options.musicId && (typeof options.musicId === 'boolean' || !/^[\w-]{1,100}$/.test(String(options.musicId)))) throw new Error('Invalid Meting ID.');
  if (options.musicId && !['tencent', 'netease', 'kugou', 'kuwo', 'migu'].includes(options.musicServer || 'tencent')) throw new Error('Invalid Meting server.');
  const files = [];
  const add = (relative, content, kind) => {
    const target = assertSafe(base, relative), stat = exists(target);
    files.push({ path: relative, content, kind, state: stat ? sameContent(target, content) ? 'unchanged' : 'existing' : 'create' });
  };
  const menu = [{ name: '首页', path: '/' }, { name: '文章', path: '/archives/' }], explore = [];
  const overrides = {};
  for (const id of pages) {
    const feature = features[id];
    assertSafe(base, path.relative(base, path.join(source, id, '.morii-check')));
    const existing = feature.generated ? { url: `/${id}/` } : pagePath(source, id);
    (feature.explore ? explore : menu).push({ name: feature.title, path: existing.url });
    if (!feature.generated) {
      const content = `---\n${yaml.dump({ title: translate(feature.title), type: feature.type, comments: id === 'comments' })}---\n`;
      const target = existing.found || path.join(source, id, 'index.md');
      add(path.relative(base, target), content, 'page');
    }
    if (feature.data) {
      const data = feature.data;
      const variants = ['yml', 'yaml', 'json'].map(extension => path.join(source, '_data', `${data}.${extension}`));
      const target = variants.find(exists) || variants[0];
      add(path.relative(base, target), `# ${translate(feature.title)} — Morii\n${data === 'series' ? '{}\n' : '[]\n'}`, 'data');
    }
    if (id === 'cinema') overrides.cinema = { enable: true };
    if (id === 'series') overrides.series = { enable: true };
  }
  if (menu.length > 2) overrides.menu = menu;
  if (explore.length) overrides.explore = explore;
  if (provider !== 'none') overrides.comments = { enable: true, provider, [provider === 'waline' ? 'server_url' : 'env_id']: endpoint };
  if (options.github) overrides.github_calendar = { enable: true, user: options.github };
  if (options.musicId) overrides.music = { meting: { enable: true, server: options.musicServer || 'tencent', type: 'playlist', id: String(options.musicId) } };
  const content = header + yaml.dump(overrides, { lineWidth: -1, noRefs: true, flowLevel: 2 });
  const original = '_config.morii.yml';
  let output = options.output;
  if (output && !/^_config\.morii(?:\.[\w-]+)?\.ya?ml$/.test(output)) throw new Error('--output must be a Morii YAML filename in the blog root.');
  if (!output) output = Object.keys(overrides).length && exists(path.join(base, original)) && !sameContent(path.join(base, original), content) ? '_config.morii.generated.yml' : original;
  add(output, content, 'config');
  const config = files.at(-1);
  if (config.state === 'existing' && (Object.keys(overrides).length || options.output)) throw new Error(`${output} already exists with different contents. Choose a new --output filename; existing files are never overwritten.`);
  return { base, files, config: overrides, output, preservesConfig: output !== original && !!exists(path.join(base, original)) };
}
function write(result) {
  // Validate every destination before creating anything, then use exclusive writes.
  result.files.forEach(file => assertSafe(result.base, file.path));
  const created = [];
  try {
    for (const file of result.files.filter(file => file.state === 'create')) {
      const destination = assertSafe(result.base, file.path);
      fs.mkdirSync(path.dirname(destination), { recursive: true });
      fs.writeFileSync(destination, file.content, { flag: 'wx' }); created.push(file);
    }
  } catch (error) {
    for (const file of created.reverse()) if (sameContent(path.join(result.base, file.path), file.content)) fs.unlinkSync(path.join(result.base, file.path));
    throw error;
  }
  return result;
}
module.exports = { features, plan, write, selected };
